from datetime import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.units import inch
from reportlab.platypus import (
    ListFlowable,
    ListItem,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from reports.styles import (
    BODY_STYLE,
    FOOTER_STYLE,
    HEADING_STYLE,
    SUBHEADING_STYLE,
    SUBTITLE_STYLE,
    TITLE_STYLE,
)


class PDFGenerator:

    SEVERITY_COLORS = {
        "Critical": "#C62828",
        "High": "#EF6C00",
        "Medium": "#F9A825",
        "Low": "#2E7D32",
        "Informational": "#1565C0",
    }

    def __init__(self, filename="guardex_security_report.pdf"):

        reports_dir = Path(__file__).resolve().parent.parent / "generated_reports"

        reports_dir.mkdir(exist_ok=True)

        self.filename = str(reports_dir / filename)
    def generate(self, report):

        doc = SimpleDocTemplate(
            self.filename,
            leftMargin=40,
            rightMargin=40,
            topMargin=40,
            bottomMargin=40,
        )

        story = []

        self._cover_page(story, report)
        self._executive_summary(story, report)
        self._knowledge_base_statistics(story, report)
        self._vulnerability_details(story, report)
        self._footer(story)

        doc.build(story)

        return self.filename

    def _cover_page(self, story, report):

        risk = report.get("risk", {})
        score = risk.get("overall_score", 0)

        story.append(Paragraph("GUARDEX AI", TITLE_STYLE))
        story.append(
            Paragraph(
                "AI Powered Web Vulnerability Assessment Report",
                SUBTITLE_STYLE,
            )
        )
        story.append(Spacer(1, 0.5 * inch))

        report_id = f"GX-{datetime.now().strftime('%Y%m%d-%H%M%S')}"

        table = Table(
            [
                ["Target", report.get("target", "N/A")],
                ["Generated On", report.get("generated_at", "N/A")],
                ["Report ID", report_id],
                ["Risk Score", f"{score}/100" + (f" ({risk['rating']})" if risk.get("rating") else "")],
                ["Classification", "CONFIDENTIAL"],
            ],
            colWidths=[2.2 * inch, 4 * inch],
        )

        table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#0B3C5D")),
                    ("TEXTCOLOR", (0, 0), (0, -1), colors.white),
                    ("BACKGROUND", (1, 0), (1, -1), colors.whitesmoke),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                    ("FONTNAME", (0, 0), (-1, -1), "Helvetica-Bold"),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
                    ("TOPPADDING", (0, 0), (-1, -1), 10),
                ]
            )
        )

        story.append(table)
        story.append(Spacer(1, 0.4 * inch))

        story.append(
            Paragraph(
                "This report was automatically generated by <b>Guardex AI</b>. "
                "It summarizes detected vulnerabilities together with AI-generated remediation recommendations.",
                BODY_STYLE,
            )
        )

        story.append(PageBreak())

    def _executive_summary(self, story, report):

        story.append(Paragraph("Executive Summary", HEADING_STYLE))

        summary = report.get("summary", "")
        story.append(Paragraph(summary.replace("\n", "<br/>"), BODY_STYLE))
        story.append(Spacer(1, 0.2 * inch))

        counts = report.get("risk", {}).get("counts", {})

        table = Table(
            [
                ["Severity", "Count"],
                ["Critical", counts.get("Critical", 0)],
                ["High", counts.get("High", 0)],
                ["Medium", counts.get("Medium", 0)],
                ["Low", counts.get("Low", 0)],
                ["Informational", counts.get("Informational", 0)],
            ],
            colWidths=[3 * inch, 2 * inch],
        )

        table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0B3C5D")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#F7F9FC")),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                    ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ]
            )
        )

        story.append(table)
        story.append(PageBreak())

    def _knowledge_base_statistics(self, story, report):

        story.append(Paragraph("Knowledge Base Statistics", HEADING_STYLE))

        stats = report.get("statistics", {})

        table = Table(
            [
                ["Metric", "Value"],
                ["Total Entries", stats.get("total_entries", 0)],
                ["Static Entries", stats.get("static_entries", 0)],
                ["Learned Entries", stats.get("learned_entries", 0)],
                ["Total Hits", stats.get("total_hits", 0)],
            ],
            colWidths=[3.5 * inch, 1.8 * inch],
        )

        table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0B3C5D")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("BACKGROUND", (0, 1), (-1, -1), colors.beige),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                    ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ]
            )
        )

        story.append(table)

        if report.get("vulnerabilities"):
            story.append(PageBreak())

    def _vulnerability_details(self, story, report):

        vulnerabilities = report.get("vulnerabilities", [])

        if not vulnerabilities:
            return

        story.append(Paragraph("Detailed Vulnerability Analysis", HEADING_STYLE))

        for index, vulnerability in enumerate(vulnerabilities, start=1):

            priority = vulnerability.get("priority", "Unknown")
            color = self.SEVERITY_COLORS.get(priority, "#000000")

            story.append(
                Paragraph(f"Finding {index}", SUBHEADING_STYLE)
            )

            info = Table(
                [
                    ["Title", vulnerability.get("title", "")],
                    ["Severity", vulnerability.get("severity", "")],
                    [
                        "Priority",
                        f"<font color='{color}'><b>{priority}</b></font>",
                    ],
                ],
                colWidths=[1.5 * inch, 4.8 * inch],
            )

            info.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#0B3C5D")),
                        ("TEXTCOLOR", (0, 0), (0, -1), colors.white),
                        ("BACKGROUND", (1, 0), (1, -1), colors.whitesmoke),
                        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                    ]
                )
            )

            story.append(info)

            story.append(Paragraph("<b>Summary</b>", SUBHEADING_STYLE))
            story.append(
                Paragraph(vulnerability.get("summary", ""), BODY_STYLE)
            )

            story.append(Paragraph("<b>Business Impact</b>", SUBHEADING_STYLE))
            story.append(
                Paragraph(vulnerability.get("business_impact", ""), BODY_STYLE)
            )

            story.append(Paragraph("<b>Technical Analysis</b>", SUBHEADING_STYLE))
            story.append(
                Paragraph(vulnerability.get("technical_analysis", ""), BODY_STYLE)
            )

            story.append(
                Paragraph("<b>Recommended Remediation</b>", SUBHEADING_STYLE)
            )

            steps = vulnerability.get("remediation_steps", [])

            if steps:
                story.append(
                    ListFlowable(
                        [
                            ListItem(Paragraph(step, BODY_STYLE))
                            for step in steps
                        ],
                        bulletType="bullet",
                    )
                )

            story.append(Spacer(1, 0.3 * inch))

    def _footer(self, story):

        story.append(PageBreak())
        story.append(Paragraph("End of Report", HEADING_STYLE))

        story.append(
            Paragraph(
                "This report is automatically generated by Guardex AI and should be reviewed before production deployment.",
                BODY_STYLE,
            )
        )

        story.append(Spacer(1, 0.3 * inch))
        story.append(
            Paragraph("Guardex AI Security Platform", SUBHEADING_STYLE)
        )

        story.append(
            Paragraph(
                f"Generated on {datetime.now().strftime('%d %B %Y %H:%M:%S')}",
                BODY_STYLE,
            )
        )

        story.append(Spacer(1, 0.4 * inch))

        story.append(
            Paragraph(
                f"© {datetime.now().year} Guardex AI. All Rights Reserved.",
                FOOTER_STYLE,
            )
        )